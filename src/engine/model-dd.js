  const sky = rect(-X1, YP, 2 * X1, Y1 - YP);   // пентащит 8×4 над краулером і контейнером
  const skyA = rect(-X1, Y0, 5, YP - Y0);        // пентащит 5×3 над асаултом
  const doorBay = seg(V(-1, YP), V(0, YP), 'door', 0, G);   // майстерня ↔ ангар важкої техніки
