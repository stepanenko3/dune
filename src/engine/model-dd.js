  const XS = X1 + R3, YF = Y0 - R3;   // бічна стіна і фронт по зовнішніх краях рядів трикутників
  const body = roundedBlock(-X1, Y0, 2 * X1, Y1 - Y0);
  const YP = 4.5;                     // стіна між переднім блоком і ангаром важкої техніки
  const c = (t) => centroid(t.p);
  // у бічних рядах трикутник, що лежить на лінії YP, — ангару: його стіна тоді від y = 4 до 9
  const back = body.filter((t) => c(t).y > YP - 1e-6), front = body.filter((t) => c(t).y < YP - 1e-6);
  // спереду середній трикутник ряду на x = 1 — гаражу: пентащит гаража тоді на 3 плити (x 0,5 … 3,5)
