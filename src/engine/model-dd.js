  const doorUp = seg(V(1, 3.5), V(1, YP), 'door', G, G + 2.5); // ангар асаулта ↔ склад

  // ===== Ангар важкої техніки: ззаду, 0 … +5 =====
  addRoom({
    id: 'bay', name: 'Ангар важкої техніки', short: 'Важка техніка', group: 'drive', z0: 0, h: TOP, roof: 'solid', eave: true,
    tiles: back, skylight: sky, label: V(0, 8.35), label3d: V(0, 9.0),
    note: 'На всю ширину бази. Краулер і контейнер грузовий опускає крізь пентащит 8×4 у даху. Сам грузовий 4×9 довший за отвір — залітає боком крізь пентащит у правій стіні і стає вздовж ангара. Усі троє разом не вміщаються. Двері в майстерню.',
    open: [seg(V(XS, 4), V(XS, 9), 'shield', 0, TOP - 0.3), doorBay],
    items: [
      item('Краулер', 'vehicle', V(-1.6, 6.3), 5.5, 2.6, 2.2, 0),
      item('Контейнер', 'vehicle', V(2.75, 6.3), 3, 2.4, 2, 0, { full: 'Вантажний контейнер грузового' }),
      item('Місце грузового 4×9', 'spot', V(0, 6.7), 9, 4, 0.02, 0, { full: 'Місце грузового (замість краулера й контейнера)' }),
    ],
  });

  // ===== Спереду, рівень 0 (2 стіни) =====
  addRoom({
    id: 'works', name: 'Майстерня', short: 'Майстерня', group: 'craft', z0: 0, h: G, roof: 'solid', eave: true,
    tiles: frontL, label: V(-2.3, 4.25),
    note: 'Базовий верстак, ремонтна станція, 5 паливних генераторів по 75 (паливні елементи — у складі). Сходи на +2 біля дверей у гараж.',
    open: [doorBay, doorLow],
    items: [
      stairs('Сходи на +2', V(0.5, 2.5), 2, 0.95, 90, 0, G),
      gen(-3.7, 3.7), gen(-2.4, 3.7), gen(-3.7, 2.45), gen(-2.4, 2.45), gen(-3.0, 1.25),
      item('Верстак', 'craft', V(-1.1, 1.5), 1.4, 1.6, 1.6, 0, { full: 'Базовий верстак', recipe: 'fabricator' }),
      item('Ремонт', 'craft', V(-1.25, 3.3), 2, 1.0, 1.2, 90, { full: 'Ремонтна станція', recipe: 'repair' }),
    ],
  });
  addRoom({
    id: 'garage', name: 'Гараж багі', short: 'Гараж багі', group: 'drive', z0: 0, h: G, roof: 'solid', eave: true,
    tiles: frontR, label: V(2.6, 4.15),
    note: 'Заїзд крізь пентащит на 3 плити у фронті — це і вхід пішки. Двері в майстерню.',
    open: [seg(V(0.5, YF), V(3.5, YF), 'shield', 0, G - 0.3), doorLow],
    items: [item('Багі', 'vehicle', V(2.6, 2.3), 3, 2, 1.4, 90)],
  });

  // ===== Спереду, рівень +2 (3 стіни) =====
