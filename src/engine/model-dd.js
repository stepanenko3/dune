  const G = 2;    // спереду: 0 … +2 майстерня і гараж, +2 … +5 ангар асаулта і склад
  const TOP = 5;  // дах; ангар важкої техніки — на всю висоту 0 … +5

  const claims = [{ x: -5, y: 0, w: 10, d: 10 }];

