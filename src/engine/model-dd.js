  const addRoom = (r) => { rooms.push(r); return r; };
  // recipe — рецепт пристрою в кошторисі (build.js, RECIPES)
  const box = (x, y) => item('Контейнер', 'storage', V(x, y), 0.9, 0.9, 2, 0, { recipe: 'storage' });
