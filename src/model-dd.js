/*
 * Модель форпосту Харконненів у Глибокій пустелі (Deep Desert) для Dune: Awakening.
 *
 * Одна ділянка 10 x 10 (x від -5 до 5, y від 0 до 10, фронт на y = 0).
 * Корпус — «кругла» вежа: ядро 8 x 7 квадратів, по колу ряд трикутників, на кутах вставки
 * (повернутий квадрат + трикутник). Від межі ділянки до корпусу по 0,13 плити з усіх боків.
 *
 * Низько, як будують у Deep Desert: 2 яруси, кожна стіна стоїть на стіні нижче.
 *   0 … +2  цех: енергія, вода, переробка, склад, консоль (середнім переробникам вистачає 2 стін);
 *   +2 … +5 ангар орні з пентащитом спереду (3 стіни — як ангари на головній базі);
 *   дах +5: вітряки, вітропастки, уступ над брамою.
 * Внутрішніх стін немає: перекриття тримаються на зовнішніх стінах (до стіни від будь-якої плити ≤ 5).
 */
(function (root) {
  'use strict';

  const GEOM = typeof module !== 'undefined' && module.exports ? require('./geom.js') : root.GEOM;
  const { R3, V, add, sub, mul, dir, centroid, pointInPoly, rect, roundedBlock, item, stairs, seg, boundaryEdges, roomEdges, tileArea, labelPoint, roomArea, edgeKey, exteriorEdgesIn } = GEOM;

  // ---------- висоти ----------
  const G = 2;    // цех 0 … +2, на +2 підлога ангара
  const TOP = 5;  // ангар +2 … +5, дах

  const claims = [{ x: -5, y: 0, w: 10, d: 10 }];

  // ---------- корпус ----------
  const X1 = 4, Y0 = 1.5, Y1 = 8.5;   // ядро квадратів: x -4 … 4, y 1,5 … 8,5
  const YF = Y0 - R3;                 // фронт: зовнішній край ряду трикутників
  const body = roundedBlock(-X1, Y0, 2 * X1, Y1 - Y0);
  // кутові вставки фронту: повернутий квадрат і трикутник, як на скріні 4
  const cR = [V(X1 - 0.5, YF), V(X1 + R3 - 0.5, Y0 - R3 - 0.5), V(X1 + R3, Y0 - 0.5)];
  const cL = cR.map((p) => V(-p.x, p.y));

  // ---------- приміщення ----------
  const rooms = [];
  const addRoom = (r) => { rooms.push(r); return r; };
  // проліт: 1 плита на 1 рівень, як у грі
  const flight = (name, x, y, ang, from, to) => stairs(name, V(x, y), to - from, 0.95, ang, from, to);
  const hatch = (name, x, y, w, z) => item(name, 'hatch', V(x, y), w, 0.95, 0.05, 0, z !== undefined ? { z } : {});
  const box = (x, y) => item('Контейнер', 'storage', V(x, y), 0.9, 0.9, 2, 0);

  addRoom({
    id: 'works', name: 'Цех', short: 'Цех', group: 'refine', z0: 0, h: G, roof: 'solid', eave: true,
    tiles: body, label: V(-1.2, 3.9),
    note: 'Один зал без перегородок, 2 стіни заввишки — середнім переробникам цього досить. Від дверей одразу консоль. Зліва два середні переробники спайсу і генератори, справа переробник руди, хімічний і 8 цистерн, посередині 4 контейнери. Сходи вздовж задньої стіни.',
    open: [seg(V(-0.5, YF), V(0.5, YF), 'door', 0, 2)],
    items: [
      item('Консоль суб-фіфу', 'console', V(0, 2.2), 1, 1, 1.4, 0),
      item('Переробник спайсу', 'refine', V(-3.2, 2.7), 2.0, 1.6, 2, 90, { full: 'Середній переробник спайсу' }),
      item('Переробник спайсу', 'refine', V(-3.2, 5.0), 2.0, 1.6, 2, 90, { full: 'Середній переробник спайсу' }),
      item('Переробник руди', 'refine', V(3.3, 2.4), 1.5, 1.5, 2, 0, { full: 'Середній переробник руди' }),
      item('Хімічний', 'refine', V(1.6, 2.4), 1.5, 1.4, 2, 0, { full: 'Хімічний переробник' }),
      ...[[-3.9, 7.0], [-2.6, 7.0], [-3.9, 8.3], [-2.6, 8.3]].map(([x, y]) => item('Генератор', 'power', V(x, y), 1.2, 1.2, 1.8, 0, { full: 'Паливний генератор' })),
      ...[4.3, 5.6, 6.9, 8.2].flatMap((y) => [2.3, 3.6].map((x) => item('Цистерна', 'water', V(x, y), 1.2, 1.2, 1.8, 0, { full: 'Середня цистерна' }))),
      box(-0.45, 5.2), box(0.45, 5.2), box(-0.45, 6.1), box(0.45, 6.1),
      flight('Сходи в ангар +2', 0, 8.0, 0, 0, G),
    ],
  });

  // Брама ангара: пентащит на весь фронт і на кутові грані, верх 0,3 — стіна (перемичка).
  const SH = [G, TOP - 0.3];
  addRoom({
    id: 'hangar', name: 'Ангар орні', short: 'Ангар орні', group: 'air', z0: G, h: TOP - G, roof: 'solid', eave: true,
    tiles: body, label: V(0, 6.0), label3d: V(0, 4.2),
    note: 'Ангар на весь верхній ярус, 3 стіни заввишки. Фронт і кутові грані — пентащит: орні залітають спереду і під кутом. Зліва асаулт (возить спайс), справа скаут. Ззаду службова смуга: прорізи сходів, сходи на дах, ремонт і 4 контейнери, щоб скинути вантаж одразу з орні. Дах тримають бічні і задня стіни.',
    open: [
      seg(V(-3.5, YF), V(3.5, YF), 'shield', ...SH),
      seg(cR[0], cR[1], 'shield', ...SH), seg(cR[1], cR[2], 'shield', ...SH),
      seg(cL[0], cL[1], 'shield', ...SH), seg(cL[1], cL[2], 'shield', ...SH),
    ],
    items: [
      item('Асаулт', 'air', V(-2.3, 3.4), 4.0, 2.7, 1.8, 90),
      item('Скаут', 'air', V(2.4, 3.2), 3.6, 2.4, 1.5, 90),
      hatch('Проріз сходів', 0, 8.0, 2),
      flight('Сходи на дах', 0, 7.0, 180, G, TOP),
      item('Ремонтна станція', 'craft', V(3.5, 7.6), 2, 1.0, 1.2, 90),
      box(-3.6, 7.2), box(-2.6, 7.2), box(-3.6, 8.2), box(-2.6, 8.2),
    ],
  });

  // Уступ над брамою (як гора над порталом ангара грузових на головній базі, але в один ярус — щоб не тягнути вгору).
  addRoom({
    id: 'pyrA', name: 'Уступ над брамою', group: 'crown', z0: TOP, h: 1, roof: 'tier',
    tiles: rect(-3, Y0, 6, 3), note: 'Один ярус на 6×3 плити над брамою ангара: стінка і скошений уступ.', open: [], items: [],
  });

  // ---------- дах: вітряки і вітропастки ----------
  const roofItems = [];
  const turbine = (x, y) => roofItems.push(item('Спрямований вітряк', 'turbine', V(x, y), 1, 1, 3, 0, { z: TOP }));
  const windtrap = (x, y) => roofItems.push(item('Велика вітропастка', 'windtrap', V(x, y), 1.5, 1.5, 2.6, 0, { z: TOP }));
  // 14 вітряків: по 3 обабіч уступу, по 1 між вітропастками, по 3 біля задньої стіни; 2 великі вітропастки.
  for (const sx of [-1, 1]) {
    for (const y of [2.0, 3.1, 4.2]) turbine(sx * 3.5, y);
    turbine(sx * 1.0, 5.3);
    turbine(sx * 3.6, 7.4);
    turbine(sx * 2.2, 8.4);
    turbine(sx * 1.0, 8.4);
    windtrap(sx * 2.9, 5.6);
  }
  roofItems.push(hatch('Люк на дах', 0, 7.0, 3, TOP));

  const exteriorEdges = exteriorEdgesIn(rooms);

  const levels = [
    { key: 'g', name: 'Рівень 0', sub: 'цех: енергія, вода, переробка, склад', z0: 0, z1: G },
    { key: 't', name: 'Рівень +2', sub: 'ангар орні', z0: G, z1: TOP },
    { key: 'r', name: 'Дах', sub: 'вітряки, вітропастки, уступ над брамою', z0: TOP, z1: 99 },
  ];

  // Тексти й налаштування сторінки для цієї бази.
  const ui = {
    store: 'dd:',
    all: 8,
    planScale: 46,
    claimsText: '1 ділянка',
    levelNames: { g: 'Рівень 0 · цех', t: 'Рівень +2 · ангар орні', r: 'Дах · вітряки, вітропастки' },
    captions: {
      g: '<span><strong>Рівень 0, 2 стіни.</strong> Один цех без перегородок. Двері посередині фронту, одразу за ними консоль. Зліва два середні переробники спайсу і 4 паливні генератори, справа переробник руди, хімічний і 8 середніх цистерн, посередині 4 контейнери. Уздовж задньої стіни — проліт сходів на +2 (стрілка).</span>',
      t: '<span><strong>Рівень +2, 3 стіни.</strong> Ангар орні на весь ярус: пентащит на фронті і кутових гранях (бірюзова лінія). Зліва асаулт, справа скаут. Ззаду службова смуга: проріз сходів знизу, сходи на дах, ремонтна станція, 4 контейнери.</span>',
      r: '<span><strong>Дах +5.</strong> Над брамою невисокий уступ у стилі головної бази. Обабіч і позаду нього 14 вітряків і 2 великі вітропастки. Люк від сходів — ззаду посередині.</span>',
    },
    cuts: { 'cut-g': [1.9, 0], 'cut-t': [4.9, G] },
    views: {
      quarter: { pos: [-15, 11, 8], target: [0, 2.0, -5] },
      front: { pos: [0, 3.5, 13], target: [0, 2.2, -5] },
      back: { pos: [8, 10, -23], target: [0, 2.2, -5] },
      top: { pos: [0, 34, -4.9], target: [0, 0, -5] },
    },
    roofTags: [[0, -0.9, 'Вітряки ×14 (1×1) · вітропастки ×2 (1,5×1,5)', 'дах ангара +5, обабіч і позаду уступу']],
    pieceRows: [
      ['Фундамент, рівень 0', (rs) => rs.filter((r) => r.z0 === 0).map((r) => r.tiles)],
      ['Перекриття +2 (підлога ангара)', (rs) => rs.filter((r) => r.id === 'hangar').map((r) => r.tiles)],
      ['Дах ангара +5', (rs) => rs.filter((r) => r.id === 'hangar').map((r) => r.tiles)],
      ['Уступ над брамою', (rs) => rs.filter((r) => r.group === 'crown').map((r) => r.tiles)],
    ],
    stages: {
      found: { note: 'Один шар: ядро 8×7 квадратів, по колу ряд трикутників, на кутах вставки (повернутий квадрат + трикутник). Перший фундамент — точно по центру ділянки: до межі лише 0,13 плити з кожного боку.' },
      ground: { name: 'Стіни цеху', note: 'Зовнішні стіни 0…+2 по всьому колу, двері посередині фронту. Перегородок немає.' },
      deck1: { name: 'Перекриття +2', note: 'Перекриття на всю площу, крім прорізу над сходами біля задньої стіни. Знизу скошений карниз.' },
      orni: { name: 'Ангар орні', note: 'Стіни +2…+5 над стінами цеху, на фронті і кутових гранях — пентащит із перемичкою зверху. Сходи на дах. Дах +5 із карнизом і люком над сходами.' },
      tops: { name: 'Уступ над брамою', note: 'Один ярус 6×3 на даху над брамою.' },
    },
  };

  const model = {
    R3, V, add, sub, mul, dir, centroid, pointInPoly,
    claims, rooms, roofItems, levels,
    boundaryEdges, roomEdges, exteriorEdges, labelPoint, roomArea, tileArea, edgeKey,
    // ангар стоїть на G — у кошторисі він іде окремим етапом «орні», як ангари на головній базі
    heights: { G, HANG: TOP - G, CAR: G, BACK: G, TOWER: 99, DECK: 99, TOP },
    bounds: { x0: -5, x1: 5, y0: 0, y1: 10 },
    key: { Y0, Y1, YF },
    ui,
  };

  if (typeof module !== 'undefined' && module.exports) module.exports = model;
  else root.BASE = model;
})(typeof window !== 'undefined' ? window : globalThis);
