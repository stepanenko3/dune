/*
 * Модель форпосту Харконненів у Глибокій пустелі (Deep Desert) для Dune: Awakening.
 *
 * Одна ділянка 10 x 10 (x від -5 до 5, y від 0 до 10, фронт на y = 0).
 * Корпус — «кругла» вежа: ядро 8 x 7 квадратів, по колу ряд трикутників, на кутах вставки
 * (повернутий квадрат + трикутник). Від межі ділянки до корпусу по 0,13 плити з усіх боків.
 *
 * Три яруси по 3 рівні, кожна стіна стоїть на стіні нижче:
 *   0 … +3  енергія, вода, склад, консоль;
 *   +3 … +6 переробка (спайс, руда, хімія);
 *   +6 … +9 ангар орні з пентащитом спереду; на даху вітряки, вітропастки і гора над брамою.
 * Внутрішніх стін немає: перекриття тримаються на зовнішніх стінах (до стіни від будь-якої плити ≤ 5).
 */
(function (root) {
  'use strict';

  const GEOM = typeof module !== 'undefined' && module.exports ? require('./geom.js') : root.GEOM;
  const { R3, V, add, sub, mul, dir, centroid, pointInPoly, rect, roundedBlock, item, stairs, seg, boundaryEdges, roomEdges, tileArea, labelPoint, roomArea, edgeKey, exteriorEdgesIn } = GEOM;

  // ---------- висоти ----------
  const G = 3;    // нижній ярус 0 … +3
  const CAR = 6;  // переробка +3 … +6, ангар орні +6 … +9
  const TOP = 9;  // дах

  const claims = [{ x: -5, y: 0, w: 10, d: 10 }];

  // ---------- корпус ----------
  const X1 = 4, Y0 = 1.5, Y1 = 8.5;   // ядро квадратів: x -4 … 4, y 1,5 … 8,5
  const YF = Y0 - R3;                 // фронт: зовнішній край ряду трикутників
  const body = roundedBlock(-X1, Y0, 2 * X1, Y1 - Y0);
  // кутові вставки фронту: повернутий квадрат і трикутник, як на скріні 4
  const cR = [V(X1 - 0.5, YF), V(X1 + R3 - 0.5, Y0 - R3 - 0.5), V(X1 + R3, Y0 - 0.5)];
  const cL = cR.map((p) => V(-p.x, p.y));

  // ---------- приміщення ----------
  const rooms = [];
  const addRoom = (r) => { rooms.push(r); return r; };
  // проліт: 3 плити на 3 рівні, як у грі (1 плита — 1 рівень)
  const flight = (name, y, ang, from, to) => stairs(name, V(0, y), 3, 0.95, ang, from, to);
  const hatch = (name, y, z) => item(name, 'hatch', V(0, y), 3, 0.95, 0.05, 0, z !== undefined ? { z } : {});
  const box = (x, y) => item('Контейнер', 'storage', V(x, y), 0.9, 0.9, 2, 0);

  addRoom({
    id: 'lower', name: 'Енергоблок і склад', short: 'Енергоблок і склад', group: 'store', z0: 0, h: G, roof: 'solid', eave: true,
    tiles: body, label: V(0, 5.4),
    note: 'Відкритий зал без перегородок: від дверей одразу консоль, зліва генератори з паливом, справа цистерни, ззаду контейнери. Сходи вздовж задньої стіни — перший проліт.',
    open: [seg(V(-0.5, YF), V(0.5, YF), 'door', 0, 2.5)],
    items: [
      item('Консоль суб-фіфу', 'console', V(0, 2.6), 1, 1, 1.4, 0),
      ...[[-3.5, 2.6], [-2.1, 2.6], [-3.5, 4.0], [-2.1, 4.0]].map(([x, y]) => item('Генератор', 'power', V(x, y), 1.2, 1.2, 1.8, 0, { full: 'Паливний генератор' })),
      item('Паливо', 'storage', V(-4.1, 5.3), 0.9, 0.9, 1.2, 0, { full: 'Паливні елементи' }),
      item('Паливо', 'storage', V(-3.1, 5.3), 0.9, 0.9, 1.2, 0, { full: 'Паливні елементи' }),
      ...[2.6, 4.0, 5.4, 6.8].flatMap((y) => [2.1, 3.5].map((x) => item('Цистерна', 'water', V(x, y), 1.2, 1.2, 2.2, 0, { full: 'Середня цистерна' }))),
      ...[[-3.9, 6.6], [-2.9, 6.6], [-3.9, 7.6], [-2.9, 7.6], [-3.4, 8.6], [2.6, 8.3], [3.6, 8.3]].map(([x, y]) => box(x, y)),
      flight('Сходи на +3', 8.0, 0, 0, G),
    ],
  });

  addRoom({
    id: 'refinery', name: 'Переробний цех', short: 'Переробка', group: 'refine', z0: G, h: CAR - G, roof: 'solid', eave: true,
    tiles: body, label: V(0, 4.6),
    note: 'Зліва два середні переробники спайсу, справа середній переробник руди і хімічний. Біля фронту контейнери під меланж і злитки. Перший проліт приходить біля задньої стіни праворуч, звідти другий веде в ангар.',
    open: [],
    items: [
      hatch('Проріз сходів', 8.0),
      flight('Сходи в ангар +6', 7.0, 180, G, CAR),
      item('Переробник спайсу', 'refine', V(-3.1, 2.9), 2.0, 1.6, 2.6, 90, { full: 'Середній переробник спайсу' }),
      item('Переробник спайсу', 'refine', V(-3.1, 5.3), 2.0, 1.6, 2.6, 90, { full: 'Середній переробник спайсу' }),
      item('Переробник руди', 'refine', V(3.1, 2.8), 1.5, 1.5, 2, 0, { full: 'Середній переробник руди' }),
      item('Хімічний', 'refine', V(3.1, 4.6), 1.5, 1.4, 2.2, 0, { full: 'Хімічний переробник' }),
      box(-1, 1.6), box(0, 1.6), box(1, 1.6), box(3.5, 7.0), box(3.5, 8.0),
    ],
  });

  // Брама ангара: пентащит на весь фронт і на кутові грані, верх 0,3 — стіна (перемичка).
  const SH = [CAR, CAR + 2.7];
  addRoom({
    id: 'hangar', name: 'Ангар орні', short: 'Ангар орні', group: 'air', z0: CAR, h: TOP - CAR, roof: 'solid', eave: true,
    tiles: body, label: V(0, 6.0), label3d: V(0, 4.2),
    note: 'Ангар на весь верхній ярус. Фронт і кутові грані — пентащит: орні залітають спереду і під кутом. Зліва асаулт (возить спайс), справа скаут. Ззаду службова смуга: прорізи сходів, сходи на дах, ремонт і два контейнери, щоб скинути вантаж одразу з орні. Дах тримають бічні і задня стіни.',
    open: [
      seg(V(-3.5, YF), V(3.5, YF), 'shield', ...SH),
      seg(cR[0], cR[1], 'shield', ...SH), seg(cR[1], cR[2], 'shield', ...SH),
      seg(cL[0], cL[1], 'shield', ...SH), seg(cL[1], cL[2], 'shield', ...SH),
    ],
    items: [
      item('Асаулт', 'air', V(-2.3, 3.4), 4.0, 2.7, 1.8, 90),
      item('Скаут', 'air', V(2.4, 3.2), 3.6, 2.4, 1.5, 90),
      hatch('Проріз сходів', 7.0),
      flight('Сходи на дах', 8.0, 0, CAR, TOP),
      item('Ремонтна станція', 'craft', V(3.5, 7.4), 2, 1.0, 1.2, 90),
      box(-3.6, 6.9), box(-3.6, 7.9),
    ],
  });

  // Гора над брамою (як над порталом ангара грузових на головній базі): ярус і гребінь.
  addRoom({
    id: 'pyrA', name: 'Гора над брамою, ярус', group: 'crown', z0: TOP, h: 1, roof: 'tier',
    tiles: rect(-3, Y0, 6, 3), note: 'Ярус на 6 плит над брамою ангара: стінка і скошений уступ.', open: [], items: [],
  });
  addRoom({
    id: 'pyrB', name: 'Гора над брамою, гребінь', group: 'crown', z0: TOP + 1, h: 0.4, roof: 'pyramid', apex: 0.8,
    tiles: rect(-2, Y0 + 1, 4, 1), note: 'Пологий гребінь.', open: [], items: [],
  });

  // ---------- дах: вітряки і вітропастки ----------
  const roofItems = [];
  const turbine = (x, y) => roofItems.push(item('Спрямований вітряк', 'turbine', V(x, y), 1, 1, 3, 0, { z: TOP }));
  const windtrap = (x, y) => roofItems.push(item('Велика вітропастка', 'windtrap', V(x, y), 1.5, 1.5, 2.6, 0, { z: TOP }));
  // 12 вітряків: по 3 обабіч гори, 4 посередині, 2 біля задньої стіни; 2 великі вітропастки.
  for (const sx of [-1, 1]) {
    for (const y of [2.0, 3.1, 4.2]) turbine(sx * 3.5, y);
    turbine(sx * 1.0, 5.3);
    turbine(sx * 1.0, 6.5);
    turbine(sx * 3.6, 7.3);
    windtrap(sx * 2.9, 5.6);
  }
  roofItems.push(hatch('Люк на дах', 8.0, TOP));

  const exteriorEdges = exteriorEdgesIn(rooms);

  const levels = [
    { key: 'g', name: 'Рівень 0', sub: 'енергія, вода, склад, консоль', z0: 0, z1: G },
    { key: 'u', name: 'Рівень +3', sub: 'переробка', z0: G, z1: CAR },
    { key: 't', name: 'Рівень +6', sub: 'ангар орні', z0: CAR, z1: TOP },
    { key: 'r', name: 'Дах', sub: 'вітряки, вітропастки, гора над брамою', z0: TOP, z1: 99 },
  ];

  // Тексти й налаштування сторінки для цієї бази.
  const ui = {
    store: 'dd:',
    all: 12,
    planScale: 46,
    claimsText: '1 ділянка',
    levelNames: { g: 'Рівень 0 · енергія, вода, склад', u: 'Рівень +3 · переробка', t: 'Рівень +6 · ангар орні', r: 'Дах · вітряки, вітропастки' },
    captions: {
      g: '<span><strong>Рівень 0.</strong> Один зал без перегородок. Двері посередині фронту, одразу за ними консоль. Зліва 4 паливні генератори і паливо, справа 8 середніх цистерн, ззаду 7 контейнерів. Уздовж задньої стіни — перший проліт сходів на +3 (стрілка).</span>',
      u: '<span><strong>Рівень +3.</strong> Переробка: зліва два середні переробники спайсу, справа середній переробник руди і хімічний. Біля фронту і ззаду праворуч контейнери під продукцію. Другий проліт іде назад уздовж задньої стіни в ангар.</span>',
      t: '<span><strong>Рівень +6.</strong> Ангар орні на весь ярус: пентащит на фронті і кутових гранях (бірюзова лінія). Зліва асаулт, справа скаут. Ззаду службова смуга: прорізи сходів, сходи на дах, ремонтна станція, два контейнери.</span>',
      r: '<span><strong>Дах +9.</strong> Над брамою невелика гора в стилі головної бази. Обабіч неї і за нею 12 вітряків і 2 великі вітропастки. Люк від сходів — ззаду посередині.</span>',
    },
    cuts: { 'cut-g': [2.9, 0], 'cut-u': [5.9, G], 'cut-t': [8.9, CAR] },
    views: {
      quarter: { pos: [-16, 14, 8], target: [0, 3.2, -5] },
      front: { pos: [0, 5, 14], target: [0, 3.6, -5] },
      back: { pos: [8, 13, -24], target: [0, 3.6, -5] },
      top: { pos: [0, 36, -4.9], target: [0, 0, -5] },
    },
    roofTags: [[0, -0.9, 'Вітряки ×12 (1×1) · вітропастки ×2 (1,5×1,5)', 'дах ангара +9, обабіч і позаду гори']],
    pieceRows: [
      ['Фундамент, рівень 0', (rs) => rs.filter((r) => r.z0 === 0).map((r) => r.tiles)],
      ['Перекриття +3', (rs) => rs.filter((r) => r.z0 === G).map((r) => r.tiles)],
      ['Перекриття +6 (підлога ангара)', (rs) => rs.filter((r) => r.z0 === CAR).map((r) => r.tiles)],
      ['Дах ангара +9', (rs) => rs.filter((r) => r.id === 'hangar').map((r) => r.tiles)],
      ['Гора над брамою', (rs) => rs.filter((r) => r.group === 'crown').map((r) => r.tiles)],
    ],
    stages: {
      found: { note: 'Один шар: ядро 8×7 квадратів, по колу ряд трикутників, на кутах вставки (повернутий квадрат + трикутник). Перший фундамент — точно по центру ділянки: до межі лише 0,13 плити з кожного боку.' },
      ground: { name: 'Стіни нижнього ярусу', note: 'Зовнішні стіни 0…+3 по всьому колу, двері посередині фронту. Перегородок немає.' },
      deck1: { name: 'Перекриття +3', note: 'Перекриття на всю площу, крім прорізу над першим прольотом сходів біля задньої стіни. Знизу скошений карниз.' },
      upper: { name: 'Стіни переробного ярусу', note: 'Стіни +3…+6 точно над нижніми, без прорізів. Сходи з +3 на +6.' },
      car: { name: 'Перекриття +6 і ангар орні', note: 'Перекриття (проріз над другим прольотом), стіни ангара +6…+9 над стінами нижче, на фронті і кутових гранях — пентащит із перемичкою зверху. Дах +9 із карнизом, люк над сходами на дах.' },
      tops: { name: 'Гора над брамою', note: 'Ярус 6×3 і гребінь 4×1 на даху над брамою.' },
    },
  };

  const model = {
    R3, V, add, sub, mul, dir, centroid, pointInPoly,
    claims, rooms, roofItems, levels,
    boundaryEdges, roomEdges, exteriorEdges, labelPoint, roomArea, tileArea, edgeKey,
    heights: { G, HANG: 3, CAR, BACK: CAR, TOWER: 99, DECK: 99, TOP },
    bounds: { x0: -5, x1: 5, y0: 0, y1: 10 },
    key: { Y0, Y1, YF },
    ui,
  };

  if (typeof module !== 'undefined' && module.exports) module.exports = model;
  else root.BASE = model;
})(typeof window !== 'undefined' ? window : globalThis);
