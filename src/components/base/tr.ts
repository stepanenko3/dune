const LEVEL_WORDS: Record<string, string> = { 'Дах': t('Дах'), 'земля': t('земля') }
/** назва рівня з даних бази: «Рівень 0 · земля», «Рівень +5», «Дах» — стандартні перекладаємо, свої — як є */
export function levelName(name: string): string {
  return String(name ?? '').split(' · ').map((p) => {
    const m = /^Рівень\s+(\S+)$/.exec(p)
    return m ? t('Рівень {z}', { z: m[1] }) : LEVEL_WORDS[p] ?? p
  }).join(' · ')
}
/** назва етапу будівництва: «Фундамент» чи рівень */
export const stageName = (name: string) => LABELS[name] ?? levelName(name)

